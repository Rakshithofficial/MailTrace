"""Optional hosted OpenAI-compatible explanation adapter."""

from __future__ import annotations

import json
import os

from .base import ExplanationInput, ExplanationProvider, ExplanationResult, HttpRequester
from .http import ModelRequestError, post_json
from .validation import ExplanationValidationError, validate_model_output


class HostedLLMProvider(ExplanationProvider):
    source = "hosted_llm"

    def __init__(
        self,
        api_key: str | None = None,
        endpoint: str | None = None,
        model: str | None = None,
        timeout: float = 8.0,
        requester: HttpRequester = post_json,
    ) -> None:
        self.api_key = api_key or os.getenv("LLM_API_KEY")
        self.endpoint = endpoint or os.getenv("LLM_API_URL")
        self.model = model or os.getenv("LLM_MODEL", "explanation-model")
        self.timeout = timeout
        self.requester = requester

    def explain(self, case: ExplanationInput) -> ExplanationResult:
        if not self.api_key or not self.endpoint:
            return unavailable(case, "LLM_API_KEY or LLM_API_URL is not configured.")
        body = json.dumps({
            "model": self.model,
            "temperature": 0,
            "response_format": {"type": "json_object"},
            "messages": [
                {"role": "system", "content": _system_prompt()},
                {"role": "user", "content": json.dumps(case.as_dict())},
            ],
        }).encode("utf-8")
        try:
            status, raw = self.requester(
                self.endpoint,
                {"Authorization": f"Bearer {self.api_key}", "Content-Type": "application/json"},
                body,
                self.timeout,
            )
            if status == 429:
                return unavailable(case, "Hosted model rate limit reached.")
            if status != 200:
                return unavailable(case, f"Hosted model returned HTTP {status}.")
            document = json.loads(raw.decode("utf-8"))
            content = document["choices"][0]["message"]["content"]
            payload = json.loads(content) if isinstance(content, str) else content
            return validate_model_output(payload, case, self.source)
        except (ModelRequestError, ExplanationValidationError, KeyError, IndexError, TypeError, UnicodeDecodeError, json.JSONDecodeError) as exc:
            return unavailable(case, "Hosted model response was unavailable or invalid.", type(exc).__name__)


def _system_prompt() -> str:
    return (
        "You explain security findings already generated by an application. "
        "Return JSON with exactly summary, explanation, recommendations. "
        "Do not add evidence, change risk score or severity, claim attacker identity "
        "or exact location, or instruct execution/opening of files or URLs. "
        "Recommendations must be defensive and grounded only in the supplied findings."
    )


def unavailable(case: ExplanationInput, message: str, error: str = "unavailable") -> ExplanationResult:
    return ExplanationResult("hosted_llm", "unavailable", "", "", [], case.risk_score, case.severity, f"{error}: {message}")
